defineMap('suhalla_desert', {
  name: 'Suhalla Desert', w: 64, h: 128, base: 'void', music: 'desert', bg: 'sand', entry: { x: 48, y: 1 },
  enc: [['Tornado Lizard'], ['Warrior Bee', 'Warrior Bee'], ['Dirty Ape'], ['Kobold', 'Kobold'], ['Brigand']], retreat: { map: 'world_gs1', x: 26, y: 57, dir: DIR.LEFT },
  build(M) {
    M.paint(0, 0, SD_ROWS, SD_LEGEND, { cliff: '#', set: 'sandcliff', faces: 1 });
    M.exit(44, 0, 8, 1, 'world_gs1', 25, 58, DIR.UP); M.exit(12, 127, 8, 1, 'world_gs1', 48, 106, DIR.DOWN);   /* the south mouth: out onto the world below the desert's south marker; the Gate is a walk east */
    M.chest(28, 38, 'Lucky Medal', 1); M.chest(12, 44, 'Cookie', 1); M.chest(58, 27, 'Virtuous Armlet', 1); M.chest(50, 45, 'Potion', 1, { mimic: 'Mimic #3' });
    M.djinni('Flash', 4, 75, { fight: true });
    M.setObj(12, 102, 'psystone');
    for (const [x, y] of [[13, 48], [18, 48], [25, 48], [35, 13], [60, 13], [39, 42], [48, 42], [59, 44]]) sdWhirlwind(M, x, y);
    M.object('tornado', 23, 68, { id: 'suhalla_tornado', tile: 'tornado', script: STORY.tempestLizard }); M.trigger(23, 68, 1, 1, STORY.tempestLizard);
    if (!G.flag('storm_lizard_done')) M.object('tornado', 18, 90, { id: 'storm_tornado', tile: 'whirlwind_big' }); M.trigger(16, 89, 5, 3, STORY.stormLizard, { once: 'storm_lizard_done' });
    M.trigger(44, 1, 8, 1, STORY.suhallaDesertEnter, { once: 'suhalla_desert_entered' });
    sdDoor(M, 3, 68, 'suhalla_desert_cave', 1, 25); sdDoor(M, 27, 67, 'suhalla_desert_cave', 25, 19);
    M.npc('sd_lost', 15, 75, { type: 'villager_m', name: 'Traveler', text: "I've been walking in circles for two days. Every dune looks the same... Don't go near the whirlwinds. Things live in them." });
    M.chest(7, 41, 'Lucky Medal', 1, { hidden: true });
  }
});
// a whirlwind on the sand: step up to it and a Tornado Lizard comes out of it
function sdWhirlwind(M, x, y) {
  M.object('statue', x, y, { id: 'whirl_' + x + '_' + y, tile: 'whirlwind', script: function* (E) {
    const r = yield* E.ambush(['Tornado Lizard'], { canFlee: true }, { say: 'The whirlwind spins closer... something is inside it!' }); if (r !== 'win') return;
    const o = G.field.map.objects.find(o => o.id === 'whirl_' + x + '_' + y); if (o) o.gone = true;
    yield E.say('The whirlwind blows itself out.');
  } });
}
function sdDoor(M, x, y, to, tx, ty) { M.setObj(x, y, 'sd_door'); M.walkable(x, y); M.exit(x, y, 1, 1, to, tx, ty, DIR.DOWN, { door: true }); }
