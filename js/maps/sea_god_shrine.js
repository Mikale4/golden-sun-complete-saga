'use strict';
const SSG_ENC = [['Giant Bat', 'Wild Wolf'], ['Angle Worm'], ['Ghost II']];
const SSG_RETREAT = { map: 'world_tla', x: 70, y: 69, dir: DIR.DOWN };
const SSG_LEGEND = { '.': 'cave_sand', 'w': 'water', 'L': 'post_water', 'o': { ground: 'cave_sand', obj: 'crystal_rock' }, 'X': 'cave_sand', 'D': 'cave_sand', 'S': 'stairs' };
function ssgCave(id, rows, exits, build, entry) {
  defineMap(id, { name: 'Shrine of the Sea God', w: rows[0].length, h: rows.length, base: 'void', music: 'lighthouse', bg: 'ruins', indoor: true, enc: SSG_ENC, retreat: SSG_RETREAT, entry,
    build(M) {
      M.paint(0, 0, rows, SSG_LEGEND, { cliff: '#', set: 'crystal', faces: 2 });
      for (const [x, y, to, tx, ty] of exits) { M.walkable(x, y); M.exit(x, y, 1, 1, to, tx, ty, DIR.DOWN); }
      if (build) build(M);
    } });
}
