# A dungeon's rooms from its reference rip: the class maps tools/tilemap.py wrote for each panel, corrected or drawn
# outright by the dungeon's config (tools/dungeons/<name>.py), become the rows of js/maps/<name>_layout.js. Letters:
# k wall, e tiled floor, : dirt, u purple floor, a sandstone floor, c cave floor, i a gap to jump, S a stepping tile,
# w water, B a bridge, l a torch, ' ' void. Every room is flood-filled from its way in (jumps across single gaps count)
# and the places that matter are reported if they cannot be reached.
#   python tools/dungeon_gen.py <name> [<panel>]     (the panel's reach map is printed when named)
import os, sys, importlib
from collections import deque
HERE = os.path.dirname(os.path.abspath(__file__)); TM = os.path.join(HERE, 'tm'); ROOT = os.path.dirname(HERE)

def rows_of(name): return [list(l.rstrip('\n')) for l in open(os.path.join(TM, name + '.txt')) if l.strip('\n')]
def pad(rows, w, h):
    rows = [r + [' '] * (w - len(r)) for r in rows][:h]
    while len(rows) < h: rows.append([' '] * w)
    return rows
def setc(rows, x0, y0, x1, y1, ch):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): rows[y][x] = ch
def block(rows, x0, y0, lines):
    for j, line in enumerate(lines):
        for i, ch in enumerate(line):
            if ch != '?': rows[y0 + j][x0 + i] = ch

# ---- reachability: every room is checked from its way in ----
OPEN = set('e:uaSBcy'); HOP = set('i')
def reach(rows, start, targets):
    H, W = len(rows), len(rows[0]); ok = lambda x, y: 0 <= x < W and 0 <= y < H and rows[y][x] in OPEN
    hop = lambda x, y: 0 <= x < W and 0 <= y < H and rows[y][x] in HOP
    seen = { start }; q = deque([start])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if ok(nx, ny) and (nx, ny) not in seen: seen.add((nx, ny)); q.append((nx, ny))
            elif hop(nx, ny) and ok(nx + dx, ny + dy) and (nx + dx, ny + dy) not in seen: seen.add((nx + dx, ny + dy)); q.append((nx + dx, ny + dy))
    bad = [k for k, p in targets.items() if p not in seen]
    return seen, bad
if __name__ == '__main__':
    sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, 'dungeons')); CFG = importlib.import_module(sys.argv[1])
    HOP = set(getattr(CFG, 'HOP', 'i'))
    out = ['// Generated by tools/dungeon_gen.py %s from the reference rip: do not edit by hand, fix the config and rerun it.' % sys.argv[1], "'use strict';", 'const %s = {' % CFG.VAR]
    for name, fn in CFG.PANELS.items():
        rows = fn(); start, targets = CFG.CHECK[name]; seen, bad = reach(rows, start, targets)
        print('   ', name, len(rows[0]), 'x', len(rows), 'reaches', len(seen), 'cells;', ('UNREACHABLE: ' + ', '.join(bad)) if bad else 'everything reachable')
        if len(sys.argv) > 2 and sys.argv[2] == name:
            for y, row in enumerate(rows): print('%2d ' % y + ''.join(('*' if (x, y) in seen and c != ' ' else c) for x, c in enumerate(row)))
        out.append('  %s: [\n' % name + ',\n'.join("    '%s'" % ''.join(r) for r in rows) + '\n  ],')
    out.append('};')
    open(os.path.join(ROOT, CFG.OUT), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
